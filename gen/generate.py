"""Write Helmus: the edit list (weights/helmus.edits), the phrasebook (weights/phrasebook.json), the persona table
(weights/persona.json), the intent test cases (tests/intents.json), and the same files for the page (web/model/).

Usage: python gen/generate.py [persona]      (persona: a module in gen/persona/, default josh)
"""
import hashlib
import importlib
import json
import os
import re
import shutil
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)

from gen import dsl  # noqa: E402

CONTENT = ["gen.lexicon", "gen.common"]


def modules(folder):
    d = os.path.join(ROOT, "gen", folder)
    return [f"gen.{folder}.{f[:-3]}" for f in sorted(os.listdir(d)) if f.endswith(".py") and f != "__init__.py"]


def check(D):
    """every source a weight reads must exist: a typo in a unit name would silently read zero"""
    names = {f"{layer}:{n}" for layer, ns in D["units"].items() for n in ns}
    groups = {"@" + e["group"] for e in D["book"] if e.get("group")} | {"@h:" + hd for hd in ("react", "answer", "ask", "fallback")}
    entries = {e["id"] for e in D["book"]}
    bad = []
    for line in D["edits"]:
        p = line.split("#")[0].split()
        if p[0] == "LINK":
            src = p[3]
            if src.startswith(("U:", "M:", "D:")) and src not in names:
                bad.append(line)
            if src.startswith("E:") and src[2:] not in entries and src[2:] not in groups:
                bad.append(line)
        if p[0] == "REG" and f"U:{p[3][2:]}" not in names and p[3] not in names:
            bad.append(line)
    if bad:
        raise SystemExit("unknown sources:\n  " + "\n  ".join(bad[:20]))


def main():
    persona = sys.argv[1] if len(sys.argv) > 1 else "josh"
    intents = ["gen.intents.core"] + [m for m in modules("intents") if m != "gen.intents.core"]
    only = os.environ.get("HELMUS_INTENTS")              # e.g. "core,smalltalk": build with these intent modules only
    if only:
        intents = [f"gen.intents.{n}" for n in only.split(",")]
    for m in CONTENT + intents + ["gen.memory", f"gen.persona.{persona}"] + [m for m in modules("phrasebook") if m.split(".")[-1].startswith(persona)]:
        importlib.import_module(m)
    from gen import topics                                # topic units from the vocabulary's themes
    for m in modules("vocabulary"):
        importlib.import_module(m)
    topics.build()
    dsl.meta_units()
    from gen import vocab
    D = dsl.DECL
    check(D)
    out = os.environ.get("HELMUS_OUT", ROOT)          # a private build folder (weights/ and tests/) for parallel work
    os.makedirs(os.path.join(out, "weights"), exist_ok=True)
    os.makedirs(os.path.join(out, "tests"), exist_ok=True)
    head = ["# Helmus: the hand-written network. Every line is one edit with its reason (after #).",
            "# Generated by gen/generate.py from the hand-written spec in gen/. Nothing here was trained or fitted.", ""]
    edits = "\n".join(head + D["edits"]) + "\n"
    files = {
        "helmus.edits": edits,
        "phrasebook.json": json.dumps(D["book"], indent=1, ensure_ascii=False),
        "persona.json": json.dumps(D["persona"], indent=1, ensure_ascii=False),
        "vocab.txt": "# English words Helmus knows to be real (hand-written in gen/vocabulary/, forms by gen/vocab.py's rules);\n"
                     "# the reader's typo rule corrects only words not in this list. Not part of the weights.\n"
                     + "\n".join(sorted(vocab.FORMS)) + "\n",
    }
    for name, text in files.items():
        with open(os.path.join(out, "weights", name), "w") as f:
            f.write(text)
    with open(os.path.join(out, "tests", "intents.json"), "w") as f:
        json.dump(D["tests"], f, indent=0)
    if out == ROOT:
        web = os.path.join(ROOT, "web", "model")
        os.makedirs(web, exist_ok=True)
        for name in files:
            shutil.copy(os.path.join(ROOT, "weights", name), os.path.join(web, name))
    n_edit = sum(1 for l in D["edits"])
    n_text = sum(len(e["texts"]) for e in D["book"])
    sha = hashlib.sha256(edits.encode()).hexdigest()[:16]
    print(f"wrote weights/: {n_edit} edit lines, {sum(len(v) for v in D['units'].values())} units "
          f"({', '.join(f'{k} {len(v)}' for k, v in D['units'].items())}), {len(D['book'])} phrasebook entries "
          f"({n_text} lines), persona {persona}, {len(D['tests'])} intent tests, {len(vocab.FORMS)} vocabulary forms; sha256 {sha}")


if __name__ == "__main__":
    main()
